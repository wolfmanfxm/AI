#!/usr/bin/env node
/**
 * Trigger Word Evaluator v2.0
 * Validates trigger word coverage, overlap, and uniqueness across all skills.
 * Node.js — zero dependencies, built-in modules only.
 *
 * Usage: node shared/scripts/trigger-eval.mjs
 * Output: reports/trigger-eval-report.md
 */

import { readdirSync, readFileSync, existsSync, mkdirSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SUITE_ROOT = join(__dirname, '..', '..');
const SKILLS_DIR = join(SUITE_ROOT, 'skills');
const REPORT_DIR = join(SUITE_ROOT, 'reports');
const REPORT_PATH = join(REPORT_DIR, 'trigger-eval-report.md');

function parseYamlList(filepath, key) {
  if (!existsSync(filepath)) return [];
  const content = readFileSync(filepath, 'utf-8');
  const pattern = new RegExp(`${key}:\\s*\\[(.*?)\\]`, 's');
  const match = content.match(pattern);
  if (!match) return [];
  return match[1]
    .split(',')
    .map(s => s.trim().replace(/^["']|["']$/g, ''))
    .filter(Boolean);
}

function main() {
  const skills = {};
  const triggersCN = new Map();  // trigger -> [skill_names]
  const triggersEN = new Map();

  for (const name of readdirSync(SKILLS_DIR).sort()) {
    const dir = join(SKILLS_DIR, name);
    if (!existsSync(join(dir, 'skill.yaml')) || name.startsWith('.')) continue;

    const cn = parseYamlList(join(dir, 'skill.yaml'), 'triggers_cn');
    const en = parseYamlList(join(dir, 'skill.yaml'), 'triggers_en');
    skills[name] = { cn, en };

    for (const t of cn) triggersCN.set(t, [...(triggersCN.get(t) || []), name]);
    for (const t of en) triggersEN.set(t, [...(triggersEN.get(t) || []), name]);
  }

  const overlapsCN = [...triggersCN].filter(([, v]) => v.length > 1);
  const overlapsEN = [...triggersEN].filter(([, v]) => v.length > 1);
  const missing = Object.entries(skills).filter(([, d]) => !d.cn.length && !d.en.length).map(([k]) => k);

  mkdirSync(REPORT_DIR, { recursive: true });
  const lines = [];
  lines.push('# Trigger Word Evaluation Report');
  lines.push('');
  lines.push(`> Generated by trigger-eval.mjs | ${Object.keys(skills).length} skills evaluated`);
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  const totalCN = Object.values(skills).reduce((s, d) => s + d.cn.length, 0);
  const totalEN = Object.values(skills).reduce((s, d) => s + d.en.length, 0);
  lines.push('| Metric | Value |');
  lines.push('|--------|-------|');
  lines.push(`| Skills evaluated | ${Object.keys(skills).length} |`);
  lines.push(`| Total CN triggers | ${totalCN} |`);
  lines.push(`| Total EN triggers | ${totalEN} |`);
  lines.push(`| CN overlaps (>1 skill) | ${overlapsCN.length} |`);
  lines.push(`| EN overlaps (>1 skill) | ${overlapsEN.length} |`);
  lines.push(`| Skills with no triggers | ${missing.length} |`);
  lines.push(`| Avg CN triggers/skill | ${(totalCN / Math.max(Object.keys(skills).length, 1)).toFixed(1)} |`);
  lines.push('');

  if (overlapsCN.length) {
    lines.push('## ⚠️ CN Trigger Overlaps');
    lines.push('');
    lines.push('| Trigger | Skills |');
    lines.push('|---------|--------|');
    for (const [t, names] of overlapsCN) lines.push(`| ${t} | ${names.join(', ')} |`);
    lines.push('');
  }
  if (overlapsEN.length) {
    lines.push('## ⚠️ EN Trigger Overlaps');
    lines.push('');
    lines.push('| Trigger | Skills |');
    lines.push('|---------|--------|');
    for (const [t, names] of overlapsEN) lines.push(`| ${t} | ${names.join(', ')} |`);
    lines.push('');
  }
  if (missing.length) {
    lines.push('## ❌ Skills Missing Triggers');
    lines.push('');
    for (const name of missing) lines.push(`- ${name}`);
    lines.push('');
  }
  lines.push('## Per-Skill Trigger Count');
  lines.push('');
  lines.push('| Skill | CN | EN |');
  lines.push('|-------|----|----|');
  for (const [name, d] of Object.entries(skills).sort()) lines.push(`| ${name} | ${d.cn.length} | ${d.en.length} |`);

  writeFileSync(REPORT_PATH, lines.join('\n'));

  console.log(`Report written to: ${REPORT_PATH}`);
  if (overlapsCN.length) console.log(`⚠️  ${overlapsCN.length} CN trigger overlaps found`);
  if (overlapsEN.length) console.log(`⚠️  ${overlapsEN.length} EN trigger overlaps found`);
  if (missing.length) console.log(`❌ ${missing.length} skills missing triggers`);
  if (!overlapsCN.length && !overlapsEN.length && !missing.length) console.log('✅ All triggers clean — no overlaps, no missing');
}

main();
