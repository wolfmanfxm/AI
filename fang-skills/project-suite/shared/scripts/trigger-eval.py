#!/usr/bin/env python3
"""
Trigger Word Evaluator v1.0
Validates trigger word coverage, overlap, and uniqueness across all skills.

Usage: python3 shared/scripts/trigger-eval.py
Output: reports/trigger-eval-report.md
"""
import os
import re
from collections import defaultdict

SUITE_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SKILLS_DIR = os.path.join(SUITE_ROOT, "skills")

def parse_yaml_list(filepath, key):
    """Parse a simple YAML list like 'triggers_cn: [a, b, c]' without pyyaml."""
    if not os.path.exists(filepath):
        return []
    with open(filepath) as f:
        content = f.read()
    # Match: key: [item1, item2, ...]
    pattern = rf'{key}:\s*\[(.*?)\]'
    match = re.search(pattern, content)
    if not match:
        return []
    items = match.group(1)
    # Split by comma, strip quotes and whitespace
    result = []
    for item in items.split(','):
        item = item.strip().strip('"').strip("'")
        if item:
            result.append(item)
    return result

def main():
    skills = {}
    all_triggers_cn = defaultdict(list)  # trigger -> [skill_names]
    all_triggers_en = defaultdict(list)

    for skill_name in sorted(os.listdir(SKILLS_DIR)):
        skill_dir = os.path.join(SKILLS_DIR, skill_name)
        if not os.path.isdir(skill_dir) or skill_name.startswith('.'):
            continue

        triggers_cn = parse_yaml_list(os.path.join(skill_dir, "skill.yaml"), "triggers_cn")
        triggers_en = parse_yaml_list(os.path.join(skill_dir, "skill.yaml"), "triggers_en")
        skills[skill_name] = {
            'cn': triggers_cn,
            'en': triggers_en,
        }

        for t in triggers_cn:
            all_triggers_cn[t].append(skill_name)
        for t in triggers_en:
            all_triggers_en[t].append(skill_name)

    # Find overlaps
    overlaps_cn = {t: names for t, names in all_triggers_cn.items() if len(names) > 1}
    overlaps_en = {t: names for t, names in all_triggers_en.items() if len(names) > 1}

    # Find skills with no triggers
    missing = [name for name, data in skills.items() if not data['cn'] and not data['en']]

    # Write report
    report_path = os.path.join(SUITE_ROOT, "reports", "trigger-eval-report.md")
    os.makedirs(os.path.dirname(report_path), exist_ok=True)

    with open(report_path, 'w') as f:
        f.write("# Trigger Word Evaluation Report\n\n")
        f.write(f"> Generated by trigger-eval.py | {len(skills)} skills evaluated\n\n")

        f.write("## Summary\n\n")
        f.write(f"| Metric | Value |\n")
        f.write(f"|--------|-------|\n")
        f.write(f"| Skills evaluated | {len(skills)} |\n")
        f.write(f"| Total CN triggers | {sum(len(d['cn']) for d in skills.values())} |\n")
        f.write(f"| Total EN triggers | {sum(len(d['en']) for d in skills.values())} |\n")
        f.write(f"| CN overlaps (>1 skill) | {len(overlaps_cn)} |\n")
        f.write(f"| EN overlaps (>1 skill) | {len(overlaps_en)} |\n")
        f.write(f"| Skills with no triggers | {len(missing)} |\n")
        f.write(f"| Avg CN triggers/skill | {sum(len(d['cn']) for d in skills.values()) / max(len(skills), 1):.1f} |\n\n")

        if overlaps_cn:
            f.write("## ⚠️ CN Trigger Overlaps\n\n")
            f.write("These triggers match multiple skills — user may need disambiguation:\n\n")
            f.write("| Trigger | Skills |\n")
            f.write("|---------|--------|\n")
            for trigger, names in sorted(overlaps_cn.items()):
                f.write(f"| {trigger} | {', '.join(names)} |\n")
            f.write("\n")

        if overlaps_en:
            f.write("## ⚠️ EN Trigger Overlaps\n\n")
            f.write("| Trigger | Skills |\n")
            f.write("|---------|--------|\n")
            for trigger, names in sorted(overlaps_en.items()):
                f.write(f"| {trigger} | {', '.join(names)} |\n")
            f.write("\n")

        if missing:
            f.write("## ❌ Skills Missing Triggers\n\n")
            for name in missing:
                f.write(f"- {name}\n")
            f.write("\n")

        f.write("## Per-Skill Trigger Count\n\n")
        f.write("| Skill | CN | EN |\n")
        f.write("|-------|----|----|\n")
        for name in sorted(skills.keys()):
            d = skills[name]
            f.write(f"| {name} | {len(d['cn'])} | {len(d['en'])} |\n")

    print(f"Report written to: {report_path}")
    if overlaps_cn:
        print(f"⚠️  {len(overlaps_cn)} CN trigger overlaps found")
    if overlaps_en:
        print(f"⚠️  {len(overlaps_en)} EN trigger overlaps found")
    if missing:
        print(f"❌ {len(missing)} skills missing triggers")
    if not overlaps_cn and not overlaps_en and not missing:
        print("✅ All triggers clean — no overlaps, no missing")

if __name__ == "__main__":
    main()
